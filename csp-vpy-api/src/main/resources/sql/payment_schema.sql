USE csp_db;

CREATE TABLE IF NOT EXISTS PAYMENT (
    PAYMENT_ID BIGINT NOT NULL AUTO_INCREMENT,
    INVOICE_ID BIGINT NOT NULL,
    INVOICE_NO VARCHAR(40) NOT NULL,
    PAID_TOTAL DECIMAL(18,2) NOT NULL,
    PAYMENT_DATE DATE NOT NULL,
    PAYER_REMARK VARCHAR(1000) NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (PAYMENT_ID),
    UNIQUE KEY UK_PAYMENT_INVOICE (INVOICE_ID),
    CONSTRAINT FK_PAYMENT_INVOICE FOREIGN KEY (INVOICE_ID) REFERENCES INVOICE (INVOICE_ID),
    CONSTRAINT CK_PAYMENT_AMOUNT CHECK (PAID_TOTAL >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
