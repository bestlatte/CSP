CREATE TABLE IF NOT EXISTS INVOICE_NUMBER_COUNTER (
    PERIOD CHAR(6) NOT NULL,
    LAST_NUMBER BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (PERIOD)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS INVOICE (
    INVOICE_ID BIGINT NOT NULL AUTO_INCREMENT,
    INVOICE_NO VARCHAR(40) NOT NULL,
    VENDOR_ID BIGINT NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    TAX_CODE VARCHAR(10) NOT NULL,
    TAX_PERCENT DECIMAL(5,2) NOT NULL,
    ITEM VARCHAR(200) NOT NULL,
    SUBTOTAL DECIMAL(18,2) NOT NULL,
    TOTAL DECIMAL(18,2) NOT NULL,
    INVOICE_DATE DATE NOT NULL,
    DUE_DATE DATE NULL,
    REMARKS VARCHAR(1000) NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (INVOICE_ID),
    UNIQUE KEY UK_INVOICE_NO (INVOICE_NO),
    KEY IX_INVOICE_STATUS (STATUS, INVOICE_ID),
    KEY IX_INVOICE_VENDOR (VENDOR_ID),
    CONSTRAINT FK_INVOICE_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES VENDOR (VENDOR_ID),
    CONSTRAINT FK_INVOICE_CURRENCY FOREIGN KEY (CURRENCY_CODE) REFERENCES CURRENCY (CURRENCY_CODE),
    CONSTRAINT FK_INVOICE_TAX FOREIGN KEY (TAX_CODE) REFERENCES TAX_RATE (TAX_CODE),
    CONSTRAINT CK_INVOICE_AMOUNTS CHECK (SUBTOTAL >= 0 AND TOTAL >= 0),
    CONSTRAINT CK_INVOICE_DATES CHECK (DUE_DATE IS NULL OR DUE_DATE >= INVOICE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
