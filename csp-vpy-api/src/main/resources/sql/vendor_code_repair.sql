-- One-time repair for the local example data after the ID-based code generator
-- produced V0105. Preserve the CSP example V0003 and renumber this vendor to
-- V0004 / ID 3. Run while no application is writing vendor data.
USE csp_db;

CREATE TEMPORARY TABLE VENDOR_REPAIR_CHECK (
    PASSED TINYINT NOT NULL CHECK (PASSED = 1)
);

START TRANSACTION;
SELECT VENDOR_ID, VENDOR_CODE FROM VENDOR ORDER BY VENDOR_ID FOR UPDATE;
SET FOREIGN_KEY_CHECKS = 0;

UPDATE VENDOR
SET VENDOR_ID = 3, VENDOR_CODE = 'V0004', UPDATED_AT = UPDATED_AT
WHERE VENDOR_ID = 4 AND VENDOR_CODE = 'V0105' AND TAX_ID = '12345671';
UPDATE VENDOR_BANK_ACCOUNT
SET VENDOR_ID = 3, UPDATED_AT = UPDATED_AT
WHERE VENDOR_ID = 4;
UPDATE VENDOR_CODE_COUNTER
SET LAST_NUMBER = 4
WHERE COUNTER_NAME = 'VENDOR';

INSERT INTO VENDOR_REPAIR_CHECK (PASSED)
SELECT IF(
    (SELECT COUNT(*) FROM VENDOR WHERE VENDOR_ID = 1 AND VENDOR_CODE = 'V0001') = 1
    AND (SELECT COUNT(*) FROM VENDOR WHERE VENDOR_ID = 2 AND VENDOR_CODE = 'V0003') = 1
    AND (SELECT COUNT(*) FROM VENDOR WHERE VENDOR_ID = 3 AND VENDOR_CODE = 'V0004') = 1
    AND (SELECT COUNT(*) FROM VENDOR WHERE VENDOR_CODE = 'V0105') = 0
    AND (SELECT COUNT(*) FROM VENDOR_BANK_ACCOUNT b
         LEFT JOIN VENDOR v ON v.VENDOR_ID = b.VENDOR_ID
         WHERE v.VENDOR_ID IS NULL) = 0
    AND (SELECT LAST_NUMBER FROM VENDOR_CODE_COUNTER WHERE COUNTER_NAME = 'VENDOR') = 4,
    1, 0
);

SET FOREIGN_KEY_CHECKS = 1;
COMMIT;
ALTER TABLE VENDOR AUTO_INCREMENT = 4;
