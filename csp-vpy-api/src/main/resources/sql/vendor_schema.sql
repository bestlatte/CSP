-- MySQL 8.0. Run before starting the API; safe to rerun for an existing database.
-- The service creates a vendor and its first bank account in one transaction.
CREATE DATABASE IF NOT EXISTS csp_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE csp_db;

CREATE TABLE IF NOT EXISTS VENDOR (
    VENDOR_ID BIGINT NOT NULL AUTO_INCREMENT,
    VENDOR_CODE VARCHAR(20) NOT NULL,
    TAX_ID CHAR(8) NOT NULL,
    VENDOR_NAME VARCHAR(200) NOT NULL,
    STATUS VARCHAR(10) NOT NULL,
    EMAIL VARCHAR(255) NULL,
    PHONE VARCHAR(30) NULL,
    ADDRESS VARCHAR(500) NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (VENDOR_ID),
    UNIQUE KEY UK_VENDOR_CODE (VENDOR_CODE),
    UNIQUE KEY UK_VENDOR_TAX_ID (TAX_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- The counter is independent of VENDOR_ID, which can be supplied by example data.
-- Locking this row while creating a vendor keeps automatic codes unique.
CREATE TABLE IF NOT EXISTS VENDOR_CODE_COUNTER (
    COUNTER_NAME VARCHAR(20) NOT NULL,
    LAST_NUMBER BIGINT NOT NULL,
    PRIMARY KEY (COUNTER_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT IGNORE INTO VENDOR_CODE_COUNTER (COUNTER_NAME, LAST_NUMBER) VALUES ('VENDOR', 0);
UPDATE VENDOR_CODE_COUNTER
SET LAST_NUMBER = GREATEST(LAST_NUMBER, (
    SELECT COALESCE(MAX(CAST(SUBSTRING(VENDOR_CODE, 2) AS UNSIGNED)), 0)
    FROM VENDOR WHERE VENDOR_CODE REGEXP '^V[0-9]+$'
))
WHERE COUNTER_NAME = 'VENDOR';

CREATE TABLE IF NOT EXISTS VENDOR_BANK_ACCOUNT (
    ACCOUNT_ID BIGINT NOT NULL AUTO_INCREMENT,
    VENDOR_ID BIGINT NOT NULL,
    BANK_CODE VARCHAR(10) NOT NULL,
    BANK_NAME VARCHAR(100) NOT NULL,
    ACCOUNT_NAME VARCHAR(200) NOT NULL,
    ACCOUNT_NUMBER VARCHAR(50) NOT NULL,
    ACCOUNT_CCY CHAR(3) NOT NULL,
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ACCOUNT_ID),
    KEY IX_BANK_VENDOR (VENDOR_ID),
    CONSTRAINT FK_BANK_VENDOR FOREIGN KEY (VENDOR_ID) REFERENCES VENDOR (VENDOR_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
